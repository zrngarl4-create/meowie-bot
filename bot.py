def _utf16_length(s):
    """
    روبیکا طول متن برای metadata رو با واحد UTF-16 می‌شمره، نه با len() پایتون.
    اموجی‌های خارج از BMP (اکثر اموجی‌هایی که استفاده می‌کنیم) هرکدوم ۲ واحد
    UTF-16 حساب می‌شن ولی len() پایتون فقط ۱ می‌شمردشون. همین اختلاف باعث
    می‌شد بازه‌ی بولد زودتر از پایان واقعی متن تموم بشه و آخر جمله بولد نباشه.
    """
    return len(s.encode("utf-16-le")) // 2


def send_message(chat_id, text, reply_to_message_id=None):
    # همون روشی که قبلاً واقعاً کار می‌کرد: نیازی به ** نیست، کل متن پیام
    # یه بازه‌ی Bold از ابتدا تا انتها می‌گیره (از_index=0 تا طول کامل متن
    # بر حسب UTF-16). اگه به هر دلیلی روبیکا رد کرد، کل بدنه‌ی پاسخ رو
    # لاگ می‌کنیم (نه فقط کد وضعیت) و بدون بولد دوباره می‌فرستیم تا
    # پیام گم نشه.
    #
    # مقدار برگشتی: True اگه پیام واقعاً تحویل داده شد، False اگه هر سه
    # تلاش (بولد + ساده + تلاش دومِ ساده) شکست خوردن. صداکننده‌هایی که
    # قبل از این تابع یه تغییر برگشت‌ناپذیر تو دیتابیس انجام دادن (مثلاً
    # کم کردن شرط و شروع یه بازی) باید این مقدار رو چک کنن، وگرنه بازیکن
    # پولش کم می‌شه ولی هیچ پیامی نمی‌بینه و بازی به‌صورت نامرئی می‌مونه
    # تا خودکار تایم‌اوت بشه (باگی که باعث نوشتن این توضیح شد).
    metadata = None
    if text:
        metadata = {
            "meta_data_parts": [
                {"from_index": 0, "length": _utf16_length(text), "type": "Bold"}
            ]
        }

    payload = {"chat_id": chat_id, "text": text}
    if metadata:
        payload["metadata"] = metadata
    if reply_to_message_id:
        payload["reply_to_message_id"] = reply_to_message_id

    try:
        resp = requests.post(f"{BASE_URL}/sendMessage", json=payload, timeout=15)
        if resp.status_code != 200:
            print("خطای HTTP در ارسال پیام (تلاش با متادیتای بولد):", resp.status_code, resp.text)
            raise RuntimeError("send with bold metadata failed, will retry plain")
        try:
            data = resp.json()
        except ValueError:
            data = None
        if isinstance(data, dict) and data.get("status") not in (None, "OK", "ok", "done", "Done"):
            print("خطای منطقی سرور در ارسال پیام (تلاش با متادیتای بولد):", data)
            raise RuntimeError("send with bold metadata returned error status, will retry plain")
        return True
    except Exception as e:
        print("پیام با متادیتای بولد ارسال نشد، تلاش دوباره بدون فرمت:", e)

    fallback_payload = {"chat_id": chat_id, "text": text}
    if reply_to_message_id:
        fallback_payload["reply_to_message_id"] = reply_to_message_id

    # قبلاً اگه همینجا هم شکست می‌خورد، تابع بی‌سروصدا تموم می‌شد و
    # صداکننده اصلاً نمی‌فهمید پیام نرسیده. حالا یه تلاش دوم کوتاه (با
    # کمی مکث) هم اضافه شده، چون خیلی از شکست‌ها موقتی/شبکه‌ای هستن.
    for attempt in (1, 2):
        try:
            resp = requests.post(f"{BASE_URL}/sendMessage", json=fallback_payload, timeout=15)
            if resp.status_code == 200:
                # باگی که قبلاً اینجا بود: فقط کد HTTP چک می‌شد، نه خودِ
                # بدنه‌ی جواب. روبیکا می‌تونه ۲۰۰ برگردونه ولی تو بدنه
                # وضعیت خطا بده (مثلاً وقتی کاربر هیچ‌وقت پیوی بات رو
                # نزده) — که باعث می‌شد send_message موفقیت گزارش بده
                # درحالی‌که پیام اصلاً نرسیده بود.
                try:
                    data = resp.json()
                except ValueError:
                    data = None
                if isinstance(data, dict) and data.get("status") not in (None, "OK", "ok", "done", "Done"):
                    print(f"خطای منطقی سرور در ارسال پیام (تلاش ساده #{attempt}):", data)
                else:
                    return True
            else:
                print(f"خطای HTTP در ارسال پیام (تلاش ساده #{attempt}):", resp.status_code, resp.text)
        except Exception as e:
            print(f"خطا در ارسال پیام (تلاش ساده #{attempt}):", e)
        if attempt == 1:
            time.sleep(1.5)

    return False


def send_message_get_id(chat_id, text):
    """
    مثل send_message ولی سعی می‌کنه message_id پیامی که فرستاده رو هم
    برگردونه (برای قابلیت «پاک کردن تبلیغ» بعداً). چون تا حالا این
    قسمت از API رو امتحان نکرده بودیم، مسیرهای مختلف پاسخ رو چک می‌کنه؛
    اگه هیچ‌کدوم نبود، پیام بازم فرستاده می‌شه ولی message_id برابر
    None برمی‌گرده (یعنی اون پیام بعداً قابل حذف خودکار نیست).
    """
    metadata = None
    if text:
        metadata = {
            "meta_data_parts": [
                {"from_index": 0, "length": _utf16_length(text), "type": "Bold"}
            ]
        }

    payload = {"chat_id": chat_id, "text": text}
    if metadata:
        payload["metadata"] = metadata

    try:
        resp = requests.post(f"{BASE_URL}/sendMessage", json=payload, timeout=6)
        if resp.status_code != 200:
            print("خطای HTTP در ارسال پیام تبلیغاتی:", resp.status_code, resp.text)
            return None
        try:
            data = resp.json()
        except ValueError:
            return None
        candidates = []
        if isinstance(data, dict):
            candidates.append(data.get("message_id"))
            inner = data.get("data")
            if isinstance(inner, dict):
                candidates.append(inner.get("message_id"))
                new_msg = inner.get("new_message")
                if isinstance(new_msg, dict):
                    candidates.append(new_msg.get("message_id"))
        for candidate in candidates:
            if candidate:
                return str(candidate)
        return None
    except Exception as e:
        print("خطا در ارسال پیام تبلیغاتی:", e)
        return None


def delete_message(chat_id, message_id):
    try:
        resp = requests.post(
            f"{BASE_URL}/deleteMessage",
            json={"chat_id": chat_id, "message_id": message_id},
            timeout=15,
        )
        if resp.status_code != 200:
            print("خطای HTTP در حذف پیام:", resp.status_code, resp.text)
            return False
        return True
    except Exception as e:
        print("خطا در حذف پیام:", e)
        return False


