def progress_bar(current, total, length=5):
    if not total:
        return "▰" * length
    ratio = max(0, min(1, current / total))
    filled = round(length * ratio)
    filled = max(0, min(length, filled))
    return "▰" * filled + "▱" * (length - filled)


